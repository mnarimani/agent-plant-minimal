def _nonlinear(dyn) -> bool:
    text = " ".join(e["python"] for e in list(dyn["f"]) + list(dyn.get("g") or []))
    return any(k in text for k in (" if ", "min(", "max(", "abs(", "sin(", "cos(", "tan(", "exp(", "sqrt(",
                                   "log(", "**", "_divide(", "pulse_value(")) or _state_products(dyn)


def _state_products(dyn) -> bool:
    """a product of two signals that both depend on states / inputs (Product block)"""
    syms = {s["symbol"] for s in dyn["states"]} | {s["symbol"] for s in dyn["inputs"]}

    def walk(ir) -> bool:
        if not isinstance(ir, dict):
            return False
        args = ir.get("args") or []
        if ir.get("op") in ("mul", "div") and sum(1 for a in args if _has_symbol(a, syms)) >= 2:
            return True
        return any(walk(a) for a in args)

    return any(walk(e.get("ir")) for e in dyn["f"])


def _has_symbol(ir, syms) -> bool:
    if not isinstance(ir, dict):
        return False
    if ir.get("op") == "symbol":
        return ir.get("value") in syms
    return any(_has_symbol(a, syms) for a in ir.get("args") or [])


