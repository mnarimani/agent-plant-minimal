def _one_line(s: str) -> str:
    return " ".join((s or "").split())


def _n(k: int, word: str) -> str:
    return "%d %s%s" % (k, word, "" if k == 1 else "s")


def _e(v) -> str:
    return "n/a" if v is None else "%.1e" % v
