def to_metadata(name: str, dyn, contract, point, trace, simulation) -> Dict[str, Any]:
    states, ins, outs = dyn["states"], dyn["inputs"], dyn["outputs"]
    tf = [r for r in dyn.get("transfer_realizations") or []]
    variables = _used_variables(contract)
    assumptions = ["Read directly from the Simulink block diagram (.slx XML), without MATLAB; parameter "
                   "values are the numbers stored in the model"
                   + (" and the MATLAB variables set by %s" % ", ".join(sorted({v["source"] for v in variables.values()}))
                      if variables else "")]
    if tf:
        assumptions.append("Transfer Fcn states are internal tf2ss (controllable canonical) coordinates, not "
                           "physical quantities: %s" % ", ".join("'%s'" % r["block_name"] for r in tf))
    if dyn.get("time_dependent"):
        assumptions.append("Source blocks inside the model (Step / Pulse Generator) make the equations depend on t")
    memory = [s for s in states if s.get("coordinate") == "discrete_memory"]
    if memory:
        assumptions.append("Blocks with discrete memory (%s) keep it in %d extra states with dx/dt = 0; update(t, x, u) "
                           "sets them at every major step of the fixed-step solver, before its stages, as Simulink does - "
                           "the results depend on the step size like in Simulink"
                           % (", ".join(sorted({"%s '%s'" % (s.get("kind"), s["block_name"]) for s in memory})), len(memory)))
        if simulation.get("model_solver") not in _FIXED:
            assumptions.append("The Simulink model uses a variable-step solver, whose steps decide when the memory is "
                               "updated; here it runs at the fixed step %g s, so it is close to Simulink, not exact"
                               % simulation["fixed_step"])
    g = {e["name"]: e["expression"] for e in dyn.get("g") or []}
    return {
        "states": [s["symbol"] for s in states],
        "state_meanings": [_state_label(s) for s in states],
        "inputs": ["%s: root Inport %s" % (s["symbol"], s["name"]) for s in ins],
        "outputs": ["%s (%s) = %s" % (o["symbol"], o["name"], g.get(o["name"], "?")) for o in outs],
        "state_equations": _state_equations(dyn),
        "parameters": _scalar_variables(variables),
        "system_type": ("Hybrid model: continuous %s dynamics with discrete memory (update at every step)"
                        if memory else "Continuous-time %s state-space model") % (
            "nonlinear" if _nonlinear(dyn) else "linear"),
        "assumptions": assumptions,
        "simulink": {
            "model": name,
            "status": "Converted directly from the .slx file and checked against its block diagram",
            "validated": True,
            "method": METHOD,
            "source": SOURCE_XML,
            "compared_with_simulink": False,
            "verified_against": VERIFIED_AGAINST,
            "python_vs_simulink": None,
            "dynamics_vs_python_model": {"points": point, "simulation": {k: v for k, v in trace.items()
                                                                         if k != "metrics"}},
            "state_equations_checked": [True] * len(states),
            "definitions": [],
            "computed_in_code": [],
            "parameter_meanings": {k: "MATLAB workspace variable (%s)" % v["source"]
                                   for k, v in variables.items() if k in _scalar_variables(variables)},
            "workspace": variables,
            "source_names": {"states": [s["block_name"] for s in states], "inputs": [s["name"] for s in ins],
                             "outputs": [o["name"] for o in outs]},
            "notes": None,
            "warnings": [],
            "simulation": simulation,
        },
    }


def _state_equations(dyn) -> List[str]:
    """one line per state: dx/dt for a continuous state; for the memory of a block, its value
    after each step (update), since its dx/dt is 0 by construction"""
    updates = {e["state"]: e["expression"] for e in dyn.get("update") or []}
    kinds = {s["symbol"]: s.get("coordinate") for s in dyn["states"]}
    return ["%s(next step) = %s   (discrete memory: set at every step, constant in between)" % (e["state"], updates[e["state"]])
            if kinds.get(e["state"]) == "discrete_memory" and e["state"] in updates else
            "d%s/dt = %s" % (e["state"], e["expression"]) for e in dyn["f"]]


