SOURCE_XML = "the .slx file itself (block diagram read from its XML, no MATLAB)"
VERIFIED_AGAINST = "the block diagram read from the .slx file"
METHOD = "slx2py (SLX_TO_Python): XML block graph -> explicit equations (no LLM)"

POINT_CHECKS = 200          # random (t, x, u) points of check 1
POINT_TOL = 1e-9            # check 1: |difference| <= tol * max(1, |derivative|)
TRACE_TOL = 1e-6            # check 2: max |output difference| <= tol * max(1, output range)
CHECK_T_FINAL = 10.0        # the app's quick simulation: unit step on input 1 at t = 1 s, 10 s
LOCK_RETRIES = 4            # Windows file locks right after unpacking (see convert_slx)
LOCK_WAIT_S = 0.5
MAX_LIST = 8                # blocks named in a reason

# fixed-step solvers of the in-app simulation (the same tableaus as the C-code route)
_FIXED = ("ode1", "ode2", "ode3", "ode4", "ode5", "ode8")


@dataclass
class DirectResult:
    ok: bool
    model: str
    message: str = ""                         # for the user, when ok (markdown)
    reason: Optional[str] = None              # why the direct route failed (plain text, for the agent)
    steps: List[Step] = field(default_factory=list)
    draft: Optional[Dict[str, Any]] = None
    tableau: Optional[List[Any]] = None       # (c, A, b) of the in-app fixed-step simulation
    out_dir: Optional[Path] = None
    missing_variables: List[str] = field(default_factory=list)   # MATLAB variables without a value
    only_variables: bool = False              # ... and they are the only reason it failed
    model_fix: Optional[str] = None           # what the user changes in the model (the C routes need it too)
    no_input: Optional[str] = None            # converted, but without an input u / an output y: why
    variable_uses: Dict[str, List[str]] = field(default_factory=dict)   # missing variable -> blocks using it


def _engine():
    """imported on first use: the engine is only needed when an .slx arrives"""
    from .slx2py.model_converter import pipeline
    from .slx2py.model_simulation import backends, comparison, contracts, inputs, integrate
    return pipeline, backends, comparison, contracts, inputs, integrate


