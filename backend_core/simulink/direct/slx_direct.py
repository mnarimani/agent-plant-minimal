"""Route 0: a Simulink model (.slx) converted directly from its XML, without MATLAB.

An .slx file is a zip of XML files (blocks, lines, parameters, solver settings). The engine in
:mod:`slx2py` (copied from the SLX_TO_Python project) reads them, builds an executable block
model (its ``model.py``) and, for continuous models, the explicit equations
xdot = f(t, x, u), y = g(t, x, u) (its ``dynamics.json``).
:func:`convert_slx` turns those equations into a draft of the plant-model agent, in the same
format as :mod:`convert` (``{"system_name", "python_code": "<dynamics(t, x, u)>",
"metadata"}``), so the rest of the chat does not care which route made the model.

This route is tried first for every uploaded .slx. It needs no MATLAB and no LLM and takes about
a second. It knows the continuous and memoryless blocks of Simulink's base library that work on
scalar and vector signals - each checked against Simulink (the list is in slx2py/__init__.py) - plus
subsystems and MATLAB Function blocks. It fails, with the reason in
``DirectResult.reason``, for:

  - blocks whose contents are not stored in the .slx file (library blocks such as the
    Aerospace Blockset 6DOF, referenced models, S-Functions),
  - matrix signals (vectors are supported), blocks it has no rule for,
  - parameters that are MATLAB workspace variables it has no value for. Their values are taken,
    as in Simulink, from the user's MATLAB scripts (``scripts``: an attached .m file, or
    ``name = value`` lines typed in the chat - see :func:`chat_assignments`) and then from the
    model's own model workspace and callbacks (PreLoadFcn / PostLoadFcn / InitFcn, stored in the
    .slx). ``DirectResult.missing_variables`` lists the ones still without a value,
  - Stateflow charts (event-driven discrete state),
  - models without any state.

Blocks with discrete memory (Memory, Derivative, Unit Delay, Zero-Order Hold, discrete integrators
and filters, Rate Limiter, Relay, Backlash) keep their memory as extra entries of x with dx/dt = 0;
the draft then also defines ``update(t, x, u)``: the new x at every major step of the fixed-step
solver, before its stages (Simulink's Update phase). Such a model is simulated with its own
fixed step, because the memory is tied to the step.

The app then falls back to the C-code routes of :mod:`intake` (c2py_export.m, or the C code
generated by Embedded Coder).

Checks of a converted model (the model is not compared with Simulink - there is no MATLAB):

  1. the engine's block model vs the drafted dynamics(t, x, u): the state derivatives at
     random points (t, x, u), so every equation is checked, not only along one trajectory,
  2. the engine's own simulation of the block model vs its extracted equations
     (the outputs, with the model's own variable-step solver, for a unit step on input 1).
"""

from __future__ import annotations

import json
import math
import re
