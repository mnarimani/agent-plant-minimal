def _failure_reason(report: Optional[Dict[str, Any]], exc: Exception) -> str:
    """The reason of a failed conversion in a few sentences (from the engine's conversion report)."""
    if not report:
        return _clean(str(exc)) or type(exc).__name__
    deps = [d for d in report.get("dependencies") or []
            if d.get("status") in ("external_definition", "missing_archive_file") and d.get("on_output_path") is not False]
    if deps:
        kinds = {"library": "library block", "referenced_model": "referenced model", "s_function": "S-Function",
                 "system_xml": "subsystem"}
        names = ["%s '%s' (%s)" % (kinds.get(d["kind"], d["kind"]), _one_line(d["block_name"]).split("/")[-1],
                                   _one_line(d.get("reference") or "")) for d in deps[:MAX_LIST]]
        more = " and %d more" % (len(deps) - MAX_LIST) if len(deps) > MAX_LIST else ""
        return ("The model uses blocks whose contents are not stored in the .slx file - they live in MATLAB "
                "toolboxes or other files, so they cannot be read without MATLAB: %s%s." % ("; ".join(names), more))
    message = _clean(report.get("error", {}).get("message") or str(exc))
    try:
        reason = _summarize(message)
    except Exception:                         # noqa: BLE001 - the full message is still a reason
        reason = message
    symbols, _only = _missing_variables(report, exc)
    if not symbols:
        return reason
    ws = report.get("workspace_variables") or {}
    unresolved = ws.get("unresolved") or {}
    why = ["%s has no value: %s." % (k, _one_line(unresolved[k]).rstrip(".")) for k in symbols if k in unresolved]
    found = sorted({v["source"] for v in (ws.get("variables") or {}).values()})
    reason += (" The variables that do have a value were read from %s." % ", ".join(found) if found else
               " Neither the model's callbacks (such as InitFcn) nor anything the user sent define them.")
    return " ".join([reason] + why + [_one_line(n) for n in ws.get("notes") or []][:3])


