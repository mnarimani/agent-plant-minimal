# the conversion
# ---------------------------------------------------------------------------------------------
def convert_slx(file_name: str, data: bytes, runs_dir, log: Callable[[str], None] = print,
                scripts=(), signals=None) -> DirectResult:
    """An uploaded .slx -> DirectResult. Never raises: a model this route cannot convert is
    ``ok=False`` with the reason in ``reason`` (for the agent) and in the failed Step.
    ``scripts``: ``(source, MATLAB code)`` of the user that define workspace variables (run before
    the model's own callbacks, like the MATLAB workspace in Simulink).
    ``signals``: the inputs / outputs the user chose on the diagram of a model without root Inports /
    Outports (a ``SignalChoice``, see ``diagram.py``).
    The files of the run are written to ``<runs_dir>/<model>_xml/`` (replaced on every run)."""
    base = PurePosixPath(file_name.replace("\\", "/")).name
    name = PurePosixPath(base).stem
    steps: List[Step] = []

    def fail(reason: str, label: str, detail: Optional[str] = None, out: Optional[Path] = None,
             missing: Optional[List[str]] = None, only_variables: bool = False,
             model_fix: Optional[str] = None) -> DirectResult:
        steps.append(Step("simulink", label, detail or reason, False))
        return DirectResult(False, name, reason=reason, steps=steps, out_dir=out, missing_variables=missing or [],
                            only_variables=only_variables, model_fix=model_fix)

    if PurePosixPath(base).suffix.lower() != ".slx":
        return fail("The direct conversion reads only the .slx format; this is a .%s file. Saved as .slx "
                    "(File > Save As in Simulink) it could be tried directly."
                    % PurePosixPath(base).suffix.lower().lstrip("."),
                    "Direct conversion from the model file: not possible for .%s"
                    % PurePosixPath(base).suffix.lower().lstrip("."))
    try:
        pipeline, backends, comparison, contracts, inputs, integrate = _engine()
    except Exception as exc:                  # noqa: BLE001 - e.g. a missing dependency
        return fail("The direct converter could not be loaded (%s: %s)." % (type(exc).__name__, exc),
                    "Direct conversion from the .slx file: converter could not be loaded")

    # one fresh folder per run: an earlier run's files may still be locked (see below)
    parent = Path(runs_dir) / ("%s_xml" % _safe(name))
    shutil.rmtree(parent, ignore_errors=True)
    out = parent / uuid.uuid4().hex[:8]
    (out / "source").mkdir(parents=True, exist_ok=True)
    log("Reading the Simulink model %s directly from its XML ..." % base)
    model_dir = out / "model"
    for attempt in range(LOCK_RETRIES + 1):
        # The engine extracts the zip into a staging folder and then renames it. On Windows a virus
        # scanner / indexer can hold the new files for a moment, and the rename fails with
        # "Access is denied" (WinError 5). That says nothing about the model: wait and try again
        # in fresh folders.
        model_dir = out / ("model" if attempt == 0 else "model_%d" % attempt)
        try:
            safe = pipeline.validate_filename(base)
            source = out / "source" / safe
            source.write_bytes(data)
            pipeline.convert_slx(source, out / ("extracted" if attempt == 0 else "extracted_%d" % attempt) / name,
                                 model_dir, scripts=list(scripts), signals=signals)
            break
        except PermissionError as exc:
            if attempt == LOCK_RETRIES:
                reason = ("The model files could not be unpacked on the server, because another program kept them "
                          "locked (%s). This is a problem of the server, not of the model - sending the model again "
                          "usually works." % exc)
                return fail(reason, "Direct conversion from the .slx file: files locked on the server", reason, out)
            time.sleep(LOCK_WAIT_S * (attempt + 1))
        except Exception as exc:              # noqa: BLE001 - the engine raises ValueError / OSError
            report = _read_json(model_dir / "conversion_report.json")
            reason = _failure_reason(report, exc)
            missing, only = _missing_variables(report, exc)
            fix = _model_fix(report, exc)
            if fix:
                return fail(fix, "The model needs a change: %s" % fix.split(":")[0], reason, out, model_fix=fix)
            result = fail(reason, "Direct conversion from the .slx file: not possible", reason, out, missing, only)
            result.variable_uses = _variable_uses(report, exc)
            return result

    contract = _read_json(model_dir / "model.json") or {}
    dyn = _read_json(model_dir / "dynamics.json") or {}
    if dyn.get("status") != "success":
        reason = _dynamics_reason(dyn)
        return fail(reason, "Direct conversion from the .slx file: no continuous equations", reason, out)
    if not dyn.get("states"):
        reason = ("The model has no state (no Integrator, Transfer Fcn or block with memory on a path to an "
                  "output): it is a static function of its inputs, so there is no dx/dt = f(t, x, u) to write.")
        return fail(reason, "Direct conversion from the .slx file: no state", reason, out)
    steps.append(Step("simulink", "Read the Simulink model %s directly from the .slx file (no MATLAB)" % name,
                      _read_summary(dyn, contract, model_dir), True))
    variables = _used_variables(contract)
    if variables:
        steps.append(Step("simulink", "MATLAB workspace variables in the parameters: %s (from %s)" % (
            ", ".join(variables), ", ".join(sorted({v["source"] for v in variables.values()}))),
            "\n".join("%s = %s  (%s)" % (k, v["value"], v["source"]) for k, v in variables.items()), True))
    missing_ports = ([NO_INPORT] if not contract.get("inputs") else []) + ([NO_OUTPUT] if not dyn.get("outputs") else [])
    no_input = " ".join(missing_ports) or None
    for text in reversed(missing_ports):
        contract.setdefault("warnings", []).insert(0, text)
    if contract.get("warnings"):
        steps.append(Step("simulink", "Notes on the model (%d)" % len(contract["warnings"]),
                          "\n".join(contract["warnings"]), True))

    try:
        code = render_dynamics(dyn)
        fn = sandbox.compile_dynamics(code)
        update_fn = sandbox.compile_update(code)
        output_fn = sandbox.compile_output(code)
        output_names = [e["name"] for e in dyn.get("g") or []]
        model = runpy.run_path(str(model_dir / "model.py"))["build_model"]()
        input_names = list(contract.get("inputs") or [])
        sim = contract.get("simulation") or {}
        t0 = float(sim.get("start_time", 0.0))
        x0 = np.asarray(model.initial_state_at(t0, {n: 0.0 for n in input_names}), dtype=float)

        # ---- check 1: every state derivative vs the block model
        log("Checking the equations against the block model ...")
        point = _check_points(fn, model, x0, input_names, t0, float(sim.get("stop_time", CHECK_T_FINAL)), update_fn,
                              output_fn, output_names)
        if not point["passed"]:
            reason = ("The equations read from the block diagram do not reproduce the block model (worst relative "
                      "difference %.1e at %d random points)." % (point["worst"], point["points"]))
            return fail(reason, "Equations vs block model: FAIL", json.dumps(point), out)
        steps.append(Step("validation", "Equations%s vs the block model: PASS at %d random points (worst relative "
                          "difference %s)" % (" and outputs y" if output_fn else "", point["points"], _e(point["worst"])),
                          None, True))

        # ---- check 2: the engine's simulations of both representations
        log("Simulating the block model and the equations ...")
        if update_fn is not None:
            trace = _check_traces_discrete(model, fn, update_fn, x0, contract, dyn, output_fn)
        else:
            trace = _check_traces(model_dir, contract, backends, comparison, contracts, inputs, integrate)
        if trace.get("passed") is False:
            reason = ("The simulated outputs of the block model and of its equations differ (worst %.1e)."
                      % trace["worst"])
            return fail(reason, "Simulated block model vs equations: FAIL", json.dumps(trace), out)
        steps.append(Step("validation", "Simulated outputs, block model vs equations: %s" % (
            "PASS (worst difference %s, %s, unit step on %s)" % (_e(trace["worst"]), trace["solver"], trace["input"])
            if trace.get("passed") else "not checked - " + trace.get("note", "")), None, True))

        # ---- the in-app simulation: fixed step, refined until it settles
        solver, tableau, h = _pick_simulation(code, x0, len(input_names), sim, _sample_times(dyn))
    except Exception as exc:                  # noqa: BLE001 - report, never crash the app
        reason = "The direct conversion failed while checking the equations (%s: %s)." % (type(exc).__name__, exc)
        return fail(reason, "Direct conversion from the .slx file: check failed", reason, out)

    simulation = {"solver": solver, "fixed_step": h, "initial_state": [float(v) for v in x0],
                  "n_inputs": len(input_names), "discrete": update_fn is not None,
                  "model_solver": sim.get("solver"), "model_step": sim.get("step_size")}
    metadata = to_metadata(name, dyn, contract, point, trace, simulation)
    draft = {"system_name": name, "python_code": code, "metadata": metadata}
    (out / ("%s_dynamics.py" % _safe(name))).write_text(code, encoding="utf-8")
    result = DirectResult(True, name, steps=steps, draft=draft, tableau=tableau, out_dir=model_dir, no_input=no_input)
    result.message = summary(result, dyn, contract)
    return result


# ---------------------------------------------------------------------------------------------
# dynamics.json -> dynamics(t, x, u)
# ---------------------------------------------------------------------------------------------
def render_dynamics(dyn: Dict[str, Any]) -> str:
    """The extracted equations as a dynamics(t, x, u) of this project (plain Python, numpy/math
    only, runs in backend_core.sandbox). States and inputs keep the symbols of the equations
    (x1.., u1..), with the Simulink block they come from as a comment."""
    from .slx2py.model_converter.dynamics_expressions import python_prelude   # the engine's own helpers
    states, ins, f = dyn["states"], dyn["inputs"], dyn["f"]
    g = dyn.get("g") or []
    body = "\n".join(e["python"] for e in list(f) + list(dyn.get("update") or []) + list(g))
    lines = ["import math", "import numpy as np", ""]
    lines += python_prelude(body)
    lines += ["", "def dynamics(t, x, u):"]
    for i, s in enumerate(states):
        lines.append("    %s = x[%d]  # %s" % (s["symbol"], i, _state_label(s)))
    for i, s in enumerate(ins):
        lines.append("    %s = u[%d]  # input %s" % (s["symbol"], i, s["name"]))
    lines.append("")
    lines.append("    dx = np.zeros(%d)" % len(states))
    for i, e in enumerate(f):
        if e["python"] in ("0.0", "0"):
            continue                          # the memory of a block: constant within a step
        lines.append("    dx[%d] = %s  # d%s/dt" % (i, e["python"], e["state"]))
    lines.append("    return dx")
    if g:
        lines += ["", "", "def output(t, x, u):",
                  '    """The outputs y of the model: its root Outports and the signals chosen as outputs."""']
        for i, s in enumerate(states):
            lines.append("    %s = x[%d]" % (s["symbol"], i))
        for i, s in enumerate(ins):
            lines.append("    %s = u[%d]" % (s["symbol"], i))
        lines += ["", "    y = np.zeros(%d)" % len(g)]
        for i, e in enumerate(g):
            lines.append("    y[%d] = %s  # %s: %s" % (i, e["python"], e["output"], e["name"]))
        lines.append("    return y")
    updates = dyn.get("update") or []
    if updates:
        index = {s["symbol"]: i for i, s in enumerate(states)}
        lines += ["", "", "def update(t, x, u):",
                  '    """The discrete memory at every major step of the fixed-step solver, before its stages',
                  "    (Simulink's Update phase): the new state vector. dx/dt of the memory is 0.\"\"\""]
        for i, s in enumerate(states):
            lines.append("    %s = x[%d]" % (s["symbol"], i))
        for i, s in enumerate(ins):
            lines.append("    %s = u[%d]" % (s["symbol"], i))
        lines += ["", "    x_new = np.array(x, dtype=float)"]
        for e in updates:
            lines.append("    x_new[%d] = %s  # %s" % (index[e["state"]], e["python"], _state_label(states[index[e["state"]]])))
        lines.append("    return x_new")
    return "\n".join(lines) + "\n"


def _state_label(s: Dict[str, Any]) -> str:
    if s.get("coordinate") == "discrete_memory":
        return "%s '%s': %s" % (s.get("kind", "block"), s["block_name"], s.get("memory", "memory"))
    if s.get("coordinate") == "integrator_output":
        return "output of Integrator '%s'" % s["block_name"]
    if s.get("coordinate") == "transfer_function_internal":
        return "Transfer Fcn '%s', internal state %d (tf2ss coordinates)" % (s["block_name"], s["local_index"] + 1)
    return "%s '%s', state %d" % (s.get("block_type", "block"), s["block_name"], s["local_index"] + 1)


