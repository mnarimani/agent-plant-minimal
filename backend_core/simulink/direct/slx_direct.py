def _model_fix(report: Optional[Dict[str, Any]], exc: Exception) -> Optional[str]:
    """The change of the model that the user must make, when nothing else stops the conversion -> text"""
    message = " ".join(((report or {}).get("error", {}).get("message") or str(exc)).split())
    if "no root Outport" in message:
        return NO_OUTPORT
    if "Unsupported block(s)" not in message or ":" not in message:
        return None
    items = [i.strip() for i in re.split(r"\s-\s(?=\w[\w-]* ')", message.split(":", 1)[1])][1:]
    sources = []
    for item in items:
        kind = next((label for key, label in DATA_SOURCES.items()
                     if "block type '%s'" % key in item or "/%s" % key in item), None)
        if kind is None:
            return None                   # another problem too: that one decides the way
        block = re.search(r"'([^']*)'", item)
        sources.append("%s '%s'" % (kind, _one_line(block.group(1)) if block else "?"))
    if not sources:
        return None
    return (DATA_SOURCES_FIX + " %s read their signal from the MATLAB workspace or a file, which is not part "
            "of the .slx file. In Simulink, replace each by an Inport block (library: Sources > In1; any name) at "
            "the top level of the model; the converted model then gets it as an input u, which can be set in the "
            "app. Save the model and upload it again." % ", ".join(sources))


def _missing_variables(report: Optional[Dict[str, Any]], exc: Exception):
    """-> (MATLAB variables without a value, True if they are the only reason the conversion failed)"""
    message = (report or {}).get("error", {}).get("message") or str(exc)
    symbols = list(dict.fromkeys(re.findall(r"workspace symbol '([^']+)'", message)))
    if not symbols:
        return [], False
    if "Unsupported block(s)" in message and ":" in message:
        items = [i.strip() for i in re.split(r"\s-\s(?=\w[\w-]* ')", message.split(":", 1)[1])][1:]
        only = all("workspace symbol '" in item for item in items)
    else:
        only = True
    deps = [d for d in (report or {}).get("dependencies") or []
            if d.get("status") in ("external_definition", "missing_archive_file") and d.get("on_output_path") is not False]
    return symbols, only and not deps


def _variable_uses(report: Optional[Dict[str, Any]], exc: Exception) -> Dict[str, List[str]]:
    """missing variable -> the blocks (and parameters) that use it, from the engine's message"""
    message = (report or {}).get("error", {}).get("message") or str(exc)
    uses: Dict[str, List[str]] = {}
    for line in message.splitlines():
        head = re.match(r"\s*-\s*(\w[\w-]*) '([^']*)' \(SID [^)]*\): (.*)", line)
        if not head:
            continue
        block = "%s '%s'" % (head.group(1), _one_line(head.group(2)))
        first = re.search(r"Parameter '(\w+)'[^.]*?references workspace symbol '([^']+)'", head.group(3))
        for name in re.findall(r"workspace symbol '([^']+)'", head.group(3)):
            where = "%s, parameter %s" % (block, first.group(1)) if first and first.group(2) == name else block
            if where not in uses.setdefault(name, []):
                uses[name].append(where)
    return uses


