def _summarize(message: str) -> str:
    """The engine lists every block it could not convert; for the agent: which block types,
    which workspace variables, and the other reasons once."""
    if "Unsupported block(s)" not in message:
        return message
    items = [i.strip() for i in re.split(r"\s-\s(?=\w[\w-]* ')", message.split(":", 1)[1])][1:] if ":" in message else []
    types, symbols, other = {}, [], []
    for item in items:
        unsupported = re.search(r"Unsupported block type '([^']+)'", item)
        found = re.findall(r"workspace symbol '([^']+)'", item)
        if unsupported:
            types[unsupported.group(1)] = types.get(unsupported.group(1), 0) + 1
        elif found:
            symbols += [name for name in found if name not in symbols]
        elif item and item not in other:
            other.append(item)
    parts = []
    if types:
        parts.append("Block types the direct conversion does not support yet: " +
                     ", ".join("%s (%d)" % (t, n) if n > 1 else t for t, n in types.items()) + ".")
    if symbols:
        parts.append("Parameters that are MATLAB workspace variables (defined in MATLAB or an init script, not "
                     "stored in the .slx file): " + ", ".join(symbols[:20]) + (" ..." if len(symbols) > 20 else "") + ".")
    parts += other[:MAX_LIST]
    return " ".join(parts) or message


