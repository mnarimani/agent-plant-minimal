# checks
# ---------------------------------------------------------------------------------------------
def _check_points(fn, model, x0: np.ndarray, input_names: List[str], t0: float, t1: float,
                  update_fn=None, output_fn=None, output_names=()) -> Dict[str, Any]:
    rng = np.random.default_rng(0)
    scale = np.maximum(1.0, np.abs(x0))
    t1 = t1 if t1 > t0 else t0 + CHECK_T_FINAL
    worst, compared = 0.0, 0
    for k in range(POINT_CHECKS):
        x = x0 + rng.standard_normal(x0.size) * scale * (0.1 if k % 2 else 2.0)
        u = rng.standard_normal(len(input_names)) * (1.0 if k % 2 else 5.0)
        t = float(rng.uniform(t0, t1))
        with np.errstate(all="ignore"):
            ref = np.asarray(model.evaluate(t, x, dict(zip(input_names, u.tolist()))).derivatives, dtype=float)
            got = np.atleast_1d(np.asarray(fn(t, x.copy(), u.copy()), dtype=float))
            if update_fn is not None:                 # and the Update phase of the memory
                ref = np.concatenate([ref, model.update(t, x, dict(zip(input_names, u.tolist())))])
                got = np.concatenate([got, np.atleast_1d(np.asarray(update_fn(t, x.copy(), u.copy()), dtype=float))])
            if output_fn is not None:                 # and the outputs y
                outputs = model.evaluate(t, x, dict(zip(input_names, u.tolist()))).outputs
                ref = np.concatenate([ref, np.asarray([float(outputs[n]) for n in output_names], dtype=float)])
                got = np.concatenate([got, np.atleast_1d(np.asarray(output_fn(t, x.copy(), u.copy()), dtype=float))])
        if got.shape != ref.shape:
            return {"passed": False, "points": k + 1, "worst": math.inf,
                    "note": "dynamics() returned %d values, the block model has %d states" % (got.size, ref.size)}
        finite = np.isfinite(ref) & np.isfinite(got)
        if not np.array_equal(np.isfinite(ref), np.isfinite(got)):
            return {"passed": False, "points": k + 1, "worst": math.inf, "note": "inf/nan differ"}
        if finite.any():
            err = np.abs(got[finite] - ref[finite]) / np.maximum(1.0, np.abs(ref[finite]))
            worst = max(worst, float(err.max()))
        compared += 1
    return {"passed": worst <= POINT_TOL, "points": compared, "worst": worst, "tolerance": POINT_TOL}


def _check_traces(model_dir: Path, contract, backends, comparison, contracts, inputs, integrate) -> Dict[str, Any]:
    """The engine's runner without its reports: model.py vs dynamics.py, the model's own solver
    settings (variable-step ode45 or its fixed-step solver), a unit step on input 1 at t = 1 s."""
    names = list(contract.get("inputs") or [])
    sim = dict(contract.get("simulation") or {})
    if not names:
        return {"passed": None, "note": "the model has no input"}
    start = float(sim.get("start_time", 0.0))
    stop = start + CHECK_T_FINAL
    if sim.get("solver") not in contracts.SUPPORTED_SOLVERS:
        sim["solver"] = "ode45"
    step = float(sim.get("step_size") or 0.01)
    if sim["solver"] != "ode45":
        stop = start + step * max(1, round(CHECK_T_FINAL / step))
    sim.update(start_time=start, stop_time=stop, step_size=min(step, (stop - start) / 100))
    try:
        settings = contracts.SimulationSettings.from_mapping(sim)
        specs = {n: {"kind": "step", "step_time": start + 1.0, "initial_value": 0.0,
                     "final_value": 1.0 if i == 0 else 0.0} for i, n in enumerate(names)}
        signals = inputs.InputSet(tuple(names), specs)
        traces = {}
        for key, backend_type in (("model", backends.ModelBackend), ("dynamics", backends.DynamicsBackend)):
            backend = backend_type(model_dir, contract)
            transitions = backend.transition_times(start, stop) if hasattr(backend, "transition_times") else ()
            trace = integrate.simulate(backend, settings, signals, transitions=transitions)
            traces[key] = trace
        grid = traces["model"].time
        aligned = {k: comparison.align(v, grid, tuple(contract["outputs"])) for k, v in traces.items()}
        metrics = comparison.compare(aligned)
    except Exception as exc:                  # noqa: BLE001 - check 1 already covers the equations
        return {"passed": None, "note": "%s: %s" % (type(exc).__name__, exc)}
    span = np.ptp(aligned["model"].outputs, axis=0) if aligned["model"].outputs.size else np.zeros(0)
    worst = 0.0
    for m in metrics:
        i = list(contract["outputs"]).index(m["output"])
        worst = max(worst, m["max_absolute_error"] / max(1.0, float(span[i])))
    return {"passed": worst <= TRACE_TOL, "worst": worst, "tolerance": TRACE_TOL, "solver": settings.solver,
            "input": names[0], "t_final": stop - start, "metrics": metrics}


def _sample_times(dyn: Dict[str, Any]) -> List[float]:
    """the sample times Ts of the discrete blocks (the hit(t, Ts, offset) of the update)"""
    found: List[float] = []

    def walk(ir):
        if isinstance(ir, dict):
            if ir.get("op") == "hit" and len(ir.get("args") or []) == 3 and ir["args"][1].get("op") == "constant":
                found.append(float(ir["args"][1]["value"]))
            for a in ir.get("args") or []:
                walk(a)
    for e in dyn.get("update") or []:
        walk(e.get("ir"))
    return sorted(set(found))


def _check_traces_discrete(model, fn, update_fn, x0: np.ndarray, contract, dyn, output_fn=None) -> Dict[str, Any]:
    """A model with discrete memory: the block model (model.py with Model.update) and the draft
    (dynamics + update) simulated step for step the same way - the model's fixed-step solver (ode5
    for a variable-step model), a unit step on input 1 at t = 1 s - and their outputs compared."""
    names = list(contract.get("inputs") or [])
    sim = dict(contract.get("simulation") or {})
    solver = sim.get("solver") if sim.get("solver") in _FIXED else "ode5"
    h = _discrete_step(float(sim.get("step_size") or 0.01), _sample_times(dyn))
    c, A, b = _tableau(solver)
    steps = int(round(CHECK_T_FINAL / h))
    g = {e["name"]: e for e in dyn.get("g") or []}
    out_names = [o["name"] for o in dyn.get("outputs") or [] if o["name"] in g]

    def u_of(t):
        return np.array([1.0 if (i == 0 and t >= 1.0) else 0.0 for i in range(len(names))])

    def run(f, update, outputs):
        x = np.asarray(x0, dtype=float).copy()
        rows = []
        with np.errstate(all="ignore"):
            for k in range(steps + 1):
                t = k * h
                x = update(t, x, u_of(t))
                rows.append(list(outputs(t, x, u_of(t))) + x.tolist())     # the outputs and the states
                if k == steps:
                    break
                ks = [f(t, x, u_of(t))]
                for i in range(1, len(b)):
                    ti = t + c[i] * h
                    ks.append(f(ti, x + h * sum(A[i][j] * ks[j] for j in range(i) if A[i][j]), u_of(ti)))
                x = x + h * sum(b[i] * ks[i] for i in range(len(b)) if b[i])
        return np.array(rows, dtype=float)

    def named(u):
        return dict(zip(names, u.tolist()))

    try:
        model_rows = run(lambda t, x, u: np.asarray(model.evaluate(t, x, named(u)).derivatives, dtype=float),
                         lambda t, x, u: model.update(t, x, named(u)),
                         lambda t, x, u: [model.evaluate(t, x, named(u)).outputs[n] for n in out_names])
        # the draft's own outputs y when it has output(), in the order of out_names
        g_names = [e["name"] for e in dyn.get("g") or []]
        draft_outputs = ((lambda t, x, u: [float(v) for v, n in zip(output_fn(t, x.copy(), u.copy()), g_names)
                                           if n in out_names]) if output_fn is not None else
                         (lambda t, x, u: [float(model.evaluate(t, x, named(u)).outputs[n]) for n in out_names]))
        draft_rows = run(lambda t, x, u: np.asarray(fn(t, x.copy(), u.copy()), dtype=float),
                         lambda t, x, u: np.asarray(update_fn(t, x.copy(), u.copy()), dtype=float),
                         draft_outputs)
    except Exception as exc:                  # noqa: BLE001 - check 1 already covers the equations
        return {"passed": None, "note": "%s: %s" % (type(exc).__name__, exc)}
    if model_rows.size == 0:
        return {"passed": None, "note": "nothing to compare"}
    finite = np.isfinite(model_rows) & np.isfinite(draft_rows)
    with np.errstate(all="ignore"):
        span = np.maximum(1.0, np.ptp(np.where(finite, model_rows, 0.0), axis=0))
        worst = float(np.max(np.where(finite, np.abs(model_rows - draft_rows), 0.0) / span))
    if not np.array_equal(np.isfinite(model_rows), np.isfinite(draft_rows)):
        worst = math.inf
    return {"passed": worst <= TRACE_TOL, "worst": worst, "tolerance": TRACE_TOL,
            "solver": "%s, h = %g s, with the discrete update" % (solver, h),
            "input": names[0] if names else "-", "t_final": CHECK_T_FINAL}


def _discrete_step(step: float, sample_times: List[float]) -> float:
    """a fixed step that divides every sample time (Simulink's fixed step must), at most ``step``"""
    from fractions import Fraction
    if not sample_times:
        return step
    base = Fraction(sample_times[0]).limit_denominator(10 ** 9)
    for ts in sample_times[1:]:
        other = Fraction(ts).limit_denominator(10 ** 9)
        base = Fraction(math.gcd(base.numerator * other.denominator, other.numerator * base.denominator),
                        base.denominator * other.denominator)
    h = float(base)
    return h / math.ceil(h / step - 1e-9) if h > step else h


def _pick_simulation(code: str, x0: np.ndarray, n_inputs: int, sim: Dict[str, Any], sample_times=()):
    """(solver, tableau, step) of the in-app simulation, which is fixed-step (convert.simulate).
    A fixed-step model keeps its solver and step. A variable-step model (ode45) runs with
    Dormand-Prince at fixed step (ode5: the same formula without the step control), starting
    from its output interval and halved until a halving changes the 10 s step response by
    less than 1e-6 of its range."""
    from ..c2py import convert
    solver = sim.get("solver")
    step = float(sim.get("step_size") or 0.01)
    max_step = sim.get("max_step")
    if isinstance(max_step, (int, float)) and max_step > 0:
        step = min(step, float(max_step))
    if solver in _FIXED:
        return solver, _tableau(solver), step
    if sandbox.compile_update(code) is not None:
        # discrete memory: the step is part of the model - no refinement; a step that hits the samples
        return "ode5", _tableau("ode5"), _discrete_step(min(step, CHECK_T_FINAL / 100), list(sample_times))
    tableau = _tableau("ode5")
    step = min(step, CHECK_T_FINAL / 100)

    def run(h):
        r = convert.simulate(code, tableau=tableau, fixed_step=h, x0=x0, n_inputs=n_inputs, t_final=CHECK_T_FINAL)
        return r if r.success and not r.diverged else None

    prev = run(step)
    for _ in range(6):
        nxt = run(step / 2)
        if prev is not None and nxt is not None:
            a, b2 = prev.x, nxt.x[::2]
            if a.shape == b2.shape:
                span = max(1.0, float(np.max(np.ptp(nxt.x, axis=0))))
                if float(np.max(np.abs(a - b2))) <= 1e-6 * span:
                    break
        step, prev = step / 2, nxt
        if CHECK_T_FINAL / step > convert.SIM_MAX_STEPS / 2:
            break
    return "ode5", tableau, step


def _tableau(solver: str) -> List[Any]:
    """(c, A, b) of a Simulink fixed-step solver: the tableaus of the C-code route (they live in
    the runtime that c2py writes into every translated model)."""
    from ..c2py import c2py
    text = c2py.RUNTIME
    ns: Dict[str, Any] = {}
    exec(text[text.index("_DP5 = ("):text.index("_ALIAS = ")], ns)   # noqa: S102 - our own constant
    c, A, b = ns["_TAB"][solver]
    return [list(c), [list(r) for r in A], list(b)]


